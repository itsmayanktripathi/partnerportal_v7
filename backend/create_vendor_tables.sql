-- Create vendors table
CREATE TABLE vendors (
    vendor_id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    legal_name           VARCHAR2(255) NOT NULL,
    trade_name           VARCHAR2(255),
    tax_id               VARCHAR2(100),
    registration_number  VARCHAR2(100),
    business_type        VARCHAR2(100),
    country_of_incorp    VARCHAR2(100),
    date_established     DATE,
    created_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Create address_types table
CREATE TABLE address_types (
    type_code   VARCHAR2(50) PRIMARY KEY,
    label       VARCHAR2(100)
);

